import AppKit
import CryptoKit

struct ClipItem: Identifiable {
    enum Kind {
        case text(String)
        case link(URL, title: String?)
        case code(String)
        case color(NSColor, literal: String)
        case image(NSImage, pixelSize: CGSize)   // 缩略图 + 原图像素；原图在 snapshot 里
        case files([String])
    }

    let id: UUID
    let kind: Kind
    let source: ClipSource
    let copiedAt: Date
    /// 原始剪贴板快照（每项：类型 → 数据），粘贴时原样写回，保真。
    /// 已写入磁盘的条目这里为 nil，粘贴时再按 id 从存储读回。
    var snapshot: [[NSPasteboard.PasteboardType: Data]]?
    let fingerprint: String
    /// 快照总字节数，容量预算按它算。
    let bytes: Int
    /// 折叠过大小写与全半角的检索文字（内容 + 来源名）。
    let searchText: NSString
    let tilt = Double.random(in: -1.4 ... 1.4)

    init(id: UUID = UUID(), kind: Kind, source: ClipSource, copiedAt: Date,
         snapshot: [[NSPasteboard.PasteboardType: Data]]?, fingerprint: String, bytes: Int? = nil) {
        self.id = id
        self.kind = kind
        self.source = source
        self.copiedAt = copiedAt
        self.snapshot = snapshot
        self.fingerprint = fingerprint
        self.bytes = bytes ?? snapshot.map(Self.byteCount) ?? 0
        searchText = SearchQuery.haystack(kind: kind, source: source)
    }

    var isImage: Bool {
        if case .image = kind { return true }
        return false
    }

    static func byteCount(_ snapshot: [[NSPasteboard.PasteboardType: Data]]) -> Int {
        snapshot.reduce(0) { sum, map in map.values.reduce(sum) { $0 + $1.count } }
    }
}

extension ClipItem {
    private static let urlNameType = NSPasteboard.PasteboardType("public.url-name")

    /// 标记为"勿记录"的剪贴板类型（密码管理器等会打这些标；清单对齐 Maccy 默认值）。
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "Pasteboard generator type",
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
        "de.petermaurer.TransientPasteboardType",
        "net.antelle.keeweb",
        "Apple Web Archive pasteboard type",
    ]

    static func isSensitive(_ types: [NSPasteboard.PasteboardType]) -> Bool {
        types.contains { ignoredTypes.contains($0.rawValue) || $0.rawValue.hasPrefix("dyn.") }
    }

    /// 类型判定顺序：文件 → 图片 → 颜色 → 链接 → 代码 → 文本（RTF 按文本处理）。
    static func capture(from pb: NSPasteboard) -> ClipItem? {
        // 敏感过滤放在最前：命中就一个字节都不读，既不进内存历史，也不可能落盘。
        guard let types = pb.types, !types.isEmpty, !isSensitive(types) else { return nil }
        guard let pbItems = pb.pasteboardItems, !pbItems.isEmpty,
              !pbItems.contains(where: { isSensitive($0.types) }) else { return nil }

        var snapshot: [[NSPasteboard.PasteboardType: Data]] = []
        for item in pbItems {
            var map: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { map[type] = data }
            }
            snapshot.append(map)
        }
        guard let first = snapshot.first, !first.isEmpty else { return nil }

        let source = ClipSource.capture(from: pb)
        _ = SourceTint.of(source)   // 取色在捕获时做完，渲染只查缓存
        func make(_ kind: Kind, _ fingerprint: String) -> ClipItem {
            ClipItem(kind: kind, source: source, copiedAt: Date(), snapshot: snapshot, fingerprint: fingerprint)
        }

        let filePaths: [String] = snapshot.compactMap { map in
            guard let data = map[.fileURL],
                  let string = String(data: data, encoding: .utf8),
                  let url = URL(string: string), url.isFileURL else { return nil }
            return url.path
        }
        if !filePaths.isEmpty {
            return make(.files(filePaths), "f:" + filePaths.joined(separator: "|"))
        }

        for type in [NSPasteboard.PasteboardType.tiff, .png] {
            if let data = first[type], let image = cardImage(from: data) {
                return make(.image(image.thumb, pixelSize: image.pixelSize), "i:" + sha256(data))
            }
        }

        if first[.color] != nil, let color = NSColor(from: pb) {
            let hex = ClipClassifier.hex(color)
            return make(.color(color, literal: hex), "c:" + hex)
        }

        let title = first[urlNameType]
            .flatMap { String(data: $0, encoding: .utf8) }?
            .trimmingCharacters(in: .whitespacesAndNewlines)
        if let data = first[.string], let string = String(data: data, encoding: .utf8),
           !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let kind = ClipClassifier.kind(for: string, source: source, title: title?.isEmpty == false ? title : nil)
            return make(kind, "t:" + string)
        }

        // 只有 RTF 的复制（Word / Pages 等）：取纯文本展示，粘贴仍是原始 RTF。
        if let data = first[.rtf],
           let attributed = NSAttributedString(rtf: data, documentAttributes: nil),
           !attributed.string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let string = attributed.string
            return make(ClipClassifier.kind(for: string, source: source, title: nil), "t:" + string)
        }

        return nil
    }

    /// 卡片用缩略图：按铺满 168 × 120（@2x）所需的尺寸取，长截图也不糊；同时给出原图像素。
    static func cardImage(from data: Data) -> (thumb: NSImage, pixelSize: CGSize)? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }
        var pixelSize = CGSize.zero
        if let props = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
           let w = props[kCGImagePropertyPixelWidth] as? CGFloat,
           let h = props[kCGImagePropertyPixelHeight] as? CGFloat {
            pixelSize = CGSize(width: w, height: h)
        }
        var maxPixel: CGFloat = 420
        if pixelSize.width > 0, pixelSize.height > 0 {
            let long = max(pixelSize.width, pixelSize.height)
            let fill = max(Layout.cardWidth * 2 / pixelSize.width, (Layout.cardHeight - Layout.cuffHeight) * 2 / pixelSize.height)
            maxPixel = min(long, min(max(long * fill, 240), 1600))
        }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: maxPixel,
        ]
        guard let cgImage = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else {
            return nil
        }
        if pixelSize == .zero { pixelSize = CGSize(width: cgImage.width, height: cgImage.height) }
        let thumb = NSImage(cgImage: cgImage, size: NSSize(width: cgImage.width, height: cgImage.height))
        return (thumb, pixelSize)
    }

    static func sha256(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }
}

// MARK: 存储记录

extension ClipItem {
    /// 写盘用的记录；快照已不在内存里时为 nil。
    var record: ClipRecord? {
        guard let snapshot else { return nil }
        let (tag, payload, title): (String, String?, String?) = {
            switch kind {
            case .text(let text): return ("text", text, nil)
            case .code(let code): return ("code", code, nil)
            case .link(let url, let title): return ("link", url.absoluteString, title)
            case .color(_, let literal): return ("color", literal, nil)
            case .image: return ("image", nil, nil)
            case .files(let paths):
                let json = (try? JSONEncoder().encode(paths)).flatMap { String(data: $0, encoding: .utf8) }
                return ("files", json, nil)
            }
        }()
        return ClipRecord(id: id, fingerprint: fingerprint, kind: tag, payload: payload, title: title,
                          copiedAt: copiedAt, sourceKind: source.storageKind, sourceBundleID: source.bundleID,
                          sourceName: source.name, itemCount: snapshot.count, bytes: bytes, snapshot: snapshot)
    }

    /// 从记录重建；图片条目需要先由调用方把缩略图解好。数据不完整时返回 nil。
    init?(record: ClipRecord, image: (thumb: NSImage, pixelSize: CGSize)?) {
        let kind: Kind
        switch (record.kind, record.payload) {
        case ("text", let text?): kind = .text(text)
        case ("code", let code?): kind = .code(code)
        case ("link", let string?):
            guard let url = URL(string: string) else { return nil }
            kind = .link(url, title: record.title)
        case ("color", let literal?):
            guard let color = ClipClassifier.parseColor(literal) else { return nil }
            kind = .color(color, literal: literal)
        case ("image", _):
            guard let image else { return nil }
            kind = .image(image.thumb, pixelSize: image.pixelSize)
        case ("files", let json?):
            guard let paths = try? JSONDecoder().decode([String].self, from: Data(json.utf8)), !paths.isEmpty else {
                return nil
            }
            kind = .files(paths)
        default:
            return nil
        }
        let source = ClipSource.restore(kind: record.sourceKind, bundleID: record.sourceBundleID, name: record.sourceName)
        self.init(id: record.id, kind: kind, source: source, copiedAt: record.copiedAt,
                  snapshot: nil, fingerprint: record.fingerprint, bytes: record.bytes)
    }
}
